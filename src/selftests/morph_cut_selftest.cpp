bool sameBits(const QImage &a, const QImage &b)
{
    return a.size() == b.size() && a.format() == b.format()
        && a.bytesPerLine() == b.bytesPerLine() && a.sizeInBytes() == b.sizeInBytes()
        && std::memcmp(a.constBits(), b.constBits(), size_t(a.sizeInBytes())) == 0;
}
QImage noise(int w, int h, unsigned seed, int base = 0, int range = 256)
{
    std::mt19937 rng(seed);
    QImage image(w, h, QImage::Format_RGB32);
    for (int y = 0; y < h; ++y) {
        auto *row = reinterpret_cast<QRgb *>(image.scanLine(y));
        for (int x = 0; x < w; ++x) {
            const int v = base + int(rng() % unsigned(range));
            row[x] = qRgb(v, v, v);
        }
    }
    return image;
}
// Normalized correlation of an interior patch avoids the occlusion boundary.
// x is the square's left edge, so the expected halfway position is 60.
double correlation(const QImage &image, const QImage &texture, int x)
{
    double sumA = 0, sumB = 0, aa = 0, bb = 0, ab = 0;
    constexpr int n = 24 * 24;
    for (int y = 12; y < 36; ++y) {
        for (int dx = 12; dx < 36; ++dx) {
            const double a = qRed(image.pixel(x + dx, 32 + y));
            const double b = qRed(texture.pixel(dx, y));
            sumA += a; sumB += b; aa += a * a; bb += b * b; ab += a * b;
        }
    }
    const double denom = std::sqrt(std::max(0.0, (aa - sumA * sumA / n) * (bb - sumB * sumB / n)));
    return denom > 0 ? (ab - sumA * sumB / n) / denom : 0;
}
std::vector<int> peaks(const QImage &image, const QImage &texture)
{
    std::vector<int> result;
    for (int x = 1; x < 127; ++x) {
        const double c = correlation(image, texture, x);
        if (c > 0.35 && c > correlation(image, texture, x - 1)
                     && c >= correlation(image, texture, x + 1)) result.push_back(x);
    }
    return result;
}
